"""Synthetic Korean handwriting for OCR tests: printed Hangul made to look hand-written.

Each syllable is drawn on its own with a random offset, slight rotation, size and ink, and the
line wanders a little, so the picture is not a clean print. The sentences are written for this
script, so the text is known exactly and no one else's copyright is involved.

Usage (from the repository root):
    python tools/ocr-lab/synth/korean_handwriting.py <output folder> [count]
It writes <name>.png and one line per picture to SOURCES.txt: file, the true text and the seed.
"""
import os
import random
import sys

from PIL import Image, ImageDraw, ImageFilter, ImageFont

FONT = "C:/Windows/Fonts/malgun.ttf"

SENTENCES = [
    "오늘은 날씨가 좋습니다.",
    "우리는 주말에 공원에 갔습니다.",
    "회의는 오후 세 시에 시작합니다.",
    "커피 한 잔 주세요.",
    "책을 읽는 것을 좋아합니다.",
    "내일 아침에 전화하겠습니다.",
    "이 문서를 확인해 주세요.",
    "시장에서 사과와 배를 샀습니다.",
    "기차표는 어디에서 살 수 있습니까?",
    "동생이 학교에서 상을 받았습니다.",
    "메모를 잊지 마세요.",
    "저녁 식사는 여섯 시입니다.",
    "바다는 파랗고 하늘은 맑습니다.",
    "우리 팀은 새 계획을 만들었습니다.",
    "비가 와서 우산을 가져왔습니다.",
    "이름과 전화번호를 적어 주세요.",
    "도서관은 아홉 시에 문을 엽니다.",
    "창문을 열고 바람을 쐬었습니다.",
    "새로운 노트북을 샀습니다.",
    "감사합니다. 다음에 또 오세요.",
]

WIDTH, HEIGHT = 1400, 260
SIZE = 84


def draw_line(text, rng):
    """One line of handwriting-like Hangul on a paper-coloured canvas."""
    paper = (248 - rng.randint(0, 10), 246 - rng.randint(0, 10), 238 - rng.randint(0, 12))
    img = Image.new("RGB", (WIDTH, HEIGHT), paper)
    ink = (rng.randint(10, 50), rng.randint(10, 50), rng.randint(40, 110))
    base = HEIGHT * 0.55
    x = 90.0
    wander = 0.0
    for ch in text:
        if ch == " ":
            x += SIZE * 0.35
            continue
        size = int(SIZE * rng.uniform(0.82, 1.18))
        font = ImageFont.truetype(FONT, size)
        wander += rng.uniform(-6, 6)
        wander *= 0.85
        glyph = Image.new("RGBA", (size * 2, size * 2), (0, 0, 0, 0))
        ImageDraw.Draw(glyph).text((size // 2, size // 4), ch, font=font, fill=ink + (255,))
        glyph = glyph.rotate(rng.uniform(-10, 10), resample=Image.BICUBIC, expand=False)
        y = base + wander + rng.uniform(-12, 12) - size * 0.7
        img.paste(glyph, (int(x - size / 2), int(y)), glyph)
        x += font.getlength(ch) * rng.uniform(0.85, 1.02) + rng.uniform(-6, 8)
    img = img.filter(ImageFilter.GaussianBlur(radius=0.6))
    noise = Image.effect_noise((WIDTH, HEIGHT), 18).convert("RGB")
    return Image.blend(img, noise, 0.06)


def make(folder, count):
    os.makedirs(folder, exist_ok=True)
    rows = []
    for i in range(count):
        seed = 1000 + i
        rng = random.Random(seed)
        text = SENTENCES[i % len(SENTENCES)]
        name = f"korean-synthetic-{i + 1:02d}.png"
        draw_line(text, rng).save(os.path.join(folder, name))
        rows.append(f"{name}\tsynthetic, generated by tools/ocr-lab/synth/korean_handwriting.py (seed {seed})\tproject's own text, MIT\ttext: {text}\n")
    with open(os.path.join(folder, "SOURCES.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.writelines(rows)
    return len(rows)


if __name__ == "__main__":
    out = sys.argv[1]
    count = int(sys.argv[2]) if len(sys.argv) > 2 else 20
    print("written", make(out, count))

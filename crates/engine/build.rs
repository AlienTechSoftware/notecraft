//! Embeds the complete HTML Welcome notebook (`docs/demo/DemoNotebook/html`, built by
//! `cargo xtask demo`) into the engine, so `notebook.welcome` can write it into any notebooks
//! folder without the repository at hand. The CMGFM sibling remains source-only for comparison.
//!
//! Without the folder (a build from a copy of the crate alone) the list is empty and the
//! command says so at run time; the build does not fail.

use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".into()));
    let notebook = manifest.join("..").join("..").join("docs").join("demo").join("DemoNotebook").join("html");
    println!("cargo:rerun-if-changed={}", notebook.display());
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_else(|_| ".".into())).join("welcome_files.rs");

    let mut files: Vec<(String, PathBuf)> = Vec::new();
    if notebook.is_dir() {
        walk(&notebook, &notebook, &mut files);
    } else {
        println!("cargo:warning=no Welcome notebook at {}; notebook.welcome will have nothing to add", notebook.display());
    }
    files.sort();

    let mut text =
        String::from("/// The Welcome notebook's files, relative path and bytes, generated by build.rs.\npub static FILES: &[(&str, &[u8])] = &[\n");
    for (rel, path) in &files {
        text.push_str(&format!("    ({:?}, include_bytes!({:?})),\n", rel, path.to_string_lossy()));
    }
    text.push_str("];\n");
    let write = fs::File::create(&out).and_then(|mut f| f.write_all(text.as_bytes()));
    if let Err(e) = write {
        println!("cargo:warning=cannot write {}: {e}", out.display());
    }
}

/// Every file under `dir`, as a forward-slash path relative to `base`.
fn walk(base: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(rd) = fs::read_dir(dir) else { return };
    for entry in rd.filter_map(|e| e.ok()) {
        let path = entry.path();
        if path.is_dir() {
            walk(base, &path, out);
        } else if let Ok(rel) = path.strip_prefix(base) {
            out.push((rel.to_string_lossy().replace('\\', "/"), path.clone()));
        }
    }
}

//! The Welcome notebook: a tour of NoteCraft, written as an ordinary notebook and carried
//! inside the engine. `docs/demo/DemoNotebook` is its source, built by `cargo xtask demo`
//! from `docs/demo/scripts/content`; `build.rs` embeds that folder here.
//!
//! The desktop app adds it to an empty notebooks folder on the first start, and the File
//! screen offers it again. It is a normal notebook once written: the user can change or
//! delete it.

use crate::error::EngineError;
use notecraft_store::StoreError;
use notecraft_store::tree::Node;
use std::fs;
use std::path::{Path, PathBuf};

// `build.rs` writes the file list into OUT_DIR. rustdoc compiles this crate without that
// variable when it runs the doctests, so the generated list is included for a real build
// and stood in for under `doc`, where nothing reads it anyway.
#[cfg(not(doc))]
include!(concat!(env!("OUT_DIR"), "/welcome_files.rs"));
#[cfg(doc)]
/// The Welcome notebook's files, relative path and bytes, generated by build.rs.
pub static FILES: &[(&str, &[u8])] = &[];

/// The notebook's title, as written in its `_node.toml`.
pub const TITLE: &str = "Welcome to NoteCraft";

/// Whether this build carries the notebook at all.
pub fn available() -> bool {
    !FILES.is_empty()
}

/// The Welcome notebook already in `tree`, by title.
pub fn installed(tree: &[Node]) -> Option<PathBuf> {
    tree.iter().find(|n| n.info.title == TITLE).map(|n| n.path.clone())
}

/// Writes the notebook into the notebooks folder `root`, in the folder `welcome-to-notecraft`,
/// and returns that folder. The bundled notebook is the one that ships: any copy already in
/// that folder, an earlier install's, is replaced, not kept beside it. Refuses when a notebook
/// of this title is already in the tree, so a second ask never replaces an open one by accident.
pub fn install(root: &Path, tree: &[Node]) -> Result<PathBuf, EngineError> {
    if !available() {
        return Err(StoreError::invalid("this build of NoteCraft carries no welcome notebook").into());
    }
    if let Some(existing) = installed(tree) {
        return Err(StoreError::invalid(format!("the welcome notebook is already here: {}", existing.display())).into());
    }
    let dir = root.join(notecraft_model::names::slug(TITLE));
    if dir.exists() {
        fs::remove_dir_all(&dir).map_err(|e| StoreError::io("replace", &dir, e))?;
    }
    for (rel, bytes) in FILES {
        let path = dir.join(rel.replace('/', std::path::MAIN_SEPARATOR_STR));
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|e| StoreError::io("create", parent, e))?;
        }
        fs::write(&path, bytes).map_err(|e| StoreError::io("write", &path, e))?;
    }
    Ok(dir)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{Output, Params, Session};
    use notecraft_store::Settings;
    use notecraft_store::testing::TempDir;

    fn params(pairs: &[(&str, &str)]) -> Params {
        pairs.iter().map(|(k, v)| (k.to_string(), v.to_string())).collect()
    }

    #[test]
    fn an_old_copy_is_replaced_not_kept_beside_it() {
        let t = TempDir::new("welcome-replace");
        let root = t.path();
        let old = root.join(notecraft_model::names::slug(TITLE));
        fs::create_dir_all(&old).expect("an old copy");
        fs::write(old.join("stale.txt"), b"old").expect("a stale file");
        let dir = install(root, &[]).expect("install over the old copy");
        assert_eq!(dir, old);
        assert!(!dir.join("stale.txt").exists(), "the old copy is gone");
        assert!(dir.join("00-start/welcome/index.html").is_file(), "the bundled start page is written");
        assert_eq!(fs::read_dir(root).expect("root").count(), 1, "no second copy beside it");
    }

    #[test]
    fn the_build_carries_the_notebook() {
        assert!(available(), "docs/demo/DemoNotebook was not embedded; run `cargo xtask demo`");
        assert!(FILES.iter().any(|(p, _)| *p == "_node.toml"));
        assert!(FILES.iter().any(|(p, _)| *p == "00-start/welcome/index.html"), "the HTML start page");
        assert!(FILES.iter().any(|(p, _)| p.starts_with("10-en/how-to/")), "the full English demo pages");
        assert!(FILES.iter().all(|(p, _)| !p.ends_with("index.md")), "the bundled notebook is fully HTML");
        let mut paths: Vec<&str> = FILES.iter().map(|(p, _)| *p).collect();
        paths.dedup();
        assert_eq!(paths.len(), FILES.len(), "no path twice");
    }

    #[test]
    fn the_command_writes_a_clean_notebook_once() {
        let t = TempDir::new("welcome");
        let mut s = Session::new(&t.path().join("nb"), Settings::at(t.path().join("s.toml"))).expect("session");
        assert!(s.tree().is_empty());
        let Ok(Output::Path(dir)) = s.run("notebook.welcome", &Params::default()) else { panic!("no path") };
        assert!(dir.ends_with("welcome-to-notecraft"), "its own folder: {}", dir.display());
        assert_eq!(s.tree().len(), 1, "the tree was reloaded");
        assert_eq!(s.tree()[0].info.title, TITLE);
        assert_eq!(installed(s.tree()), Some(s.tree()[0].path.clone()));
        // The store's checker is happy, and the first page is the start page.
        match s.run("notebook.check", &params(&[("path", &dir.to_string_lossy())])).expect("check") {
            Output::Report(r) => assert!(r.problems.is_empty(), "{:?}", r.problems),
            other => panic!("{other:?}"),
        }
        let first = &s.tree()[0].children[0];
        assert_eq!(first.info.title, "Start here");
        // A second ask is refused, and nothing else appears.
        let err = s.run("notebook.welcome", &Params::default()).expect_err("refused");
        assert!(err.to_string().contains("already here"), "{err}");
        assert_eq!(s.tree().len(), 1);
    }
}

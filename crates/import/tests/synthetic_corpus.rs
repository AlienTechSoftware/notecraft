use std::fs;
use std::path::{Path, PathBuf};

use notecraft_import::{Options, run};
use notecraft_model::PageFormat;
use notecraft_store::testing::TempDir;

#[path = "support/synthetic_corpus.rs"]
mod synthetic_corpus;

const FIXTURES: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/synthetic");

fn fixture(name: &str) -> PathBuf {
    Path::new(FIXTURES).join(name)
}

fn quiet(_: &notecraft_import::Event<'_>) {}

fn one_files(root: &Path) -> Vec<String> {
    let mut files: Vec<_> = fs::read_dir(root)
        .expect("fixture directory")
        .map(|entry| entry.expect("fixture entry").file_name().to_string_lossy().into_owned())
        .filter(|name| name.ends_with(".one"))
        .collect();
    files.sort();
    files
}

fn page_with(root: &Path, page_file: &str, content: &str) -> Option<(PathBuf, String)> {
    for entry in fs::read_dir(root).ok()? {
        let path = entry.ok()?.path();
        if path.is_dir() {
            if let Some(page) = page_with(&path, page_file, content) {
                return Some(page);
            }
        } else if path.file_name().is_some_and(|name| name == page_file) {
            let page = fs::read_to_string(&path).ok()?;
            if page.contains(content) {
                return Some((path, page));
            }
        }
    }
    None
}

#[test]
fn generator_reproduces_every_checked_in_section_byte_for_byte() {
    let generated = TempDir::new("synthetic-fixture-generation");
    synthetic_corpus::generate(generated.path()).expect("generate synthetic fixtures");
    let checked_in = Path::new(FIXTURES);
    let names = one_files(checked_in);
    assert_eq!(one_files(generated.path()), names, "generator case list is stable");
    for name in names {
        assert_eq!(
            fs::read(generated.path().join(&name)).expect("generated file"),
            fs::read(checked_in.join(&name)).expect("checked-in file"),
            "generated bytes match: {name}"
        );
    }
}

#[test]
fn generated_fixture_set_has_the_documented_cases() {
    let readme = fs::read_to_string(fixture("README.md")).expect("synthetic corpus README");
    for case in ["rich-content.one", "page-hierarchy.one", "formatted-text.one", "asset-pack.one", "versions (On 1-2-2026).one", "broken.one"] {
        assert!(fixture(case).is_file(), "documented synthetic case exists: {case}");
        assert!(readme.contains(case), "README describes synthetic case: {case}");
    }
    assert!(readme.contains("generated by NoteCraft"));
}

#[test]
fn synthetic_corpus_imports_without_loss_of_supported_content_in_both_formats() {
    let source = Path::new(FIXTURES);
    let original_files: Vec<_> = [
        "rich-content.one",
        "page-hierarchy.one",
        "formatted-text.one",
        "asset-pack.one",
        "versions (On 1-2-2026).one",
        "versions (On 1-2-2025).one",
        "broken.one",
    ]
    .into_iter()
    .map(|name| (name, fs::read(fixture(name)).expect("source fixture")))
    .collect();

    for (format, page_file, bold) in
        [(PageFormat::Html, "index.html", "<b>synthetic bold</b>"), (PageFormat::Cmgfm, "index.md", "**synthetic bold**")]
    {
        let temp = TempDir::new("synthetic-import-corpus");
        let dest = temp.path().join("notebooks");
        let mut options = Options::new(source, &dest);
        options.format = format;
        let report = run(&options, &mut quiet).expect("import synthetic corpus");

        assert_eq!((report.sections_planned, report.sections_imported), (8, 7), "{report}");
        assert_eq!((report.pages, report.subpages, report.deepest, report.rtl_pages), (12, 3, 3, 1), "{report}");
        assert_eq!((report.images, report.files, report.loss.missing_data), (2, 1, 1), "{report}");
        assert_eq!(report.older_copies_left, 1);
        assert_eq!(report.skipped.len(), 1, "the damaged section is isolated: {report}");

        let root = dest.join("synthetic");
        let rich = fs::read_to_string(root.join("rich-content").join("start").join(page_file)).expect("rich page");
        assert!(rich.contains("synthetic plain text") && rich.contains(bold), "{rich}");
        let (_, arabic) = page_with(&root.join("rich-content"), page_file, "مرحبا بالعالم").expect("RTL page");
        assert!(arabic.contains("نص تجريبي آمن"), "{arabic}");

        let (assets_file, assets_page) = page_with(&root.join("asset-pack"), page_file, "synthetic assets stay attached").expect("asset page");
        let assets_page_dir = assets_file.parent().expect("asset page folder");
        assert!(assets_page.contains("sample.png") && assets_page.contains("raster sample"), "{assets_page}");
        assert!(assets_page.contains("sample.svg") && assets_page.contains("vector sample"), "{assets_page}");
        assert!(assets_page.contains("notes.txt") && !assets_page.contains("missing.png"), "{assets_page}");
        let pixel = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/synthetic-pixel.png");
        assert_eq!(fs::read(assets_page_dir.join("assets").join("sample.png")).expect("PNG output"), fs::read(pixel).expect("synthetic pixel"));
        assert!(assets_page_dir.join("assets").join("sample.svg").is_file());
        assert_eq!(fs::read(assets_page_dir.join("assets").join("notes.txt")).expect("file output"), b"Synthetic attachment content.\n");

        let current = fs::read_to_string(root.join("versions").join("current").join(page_file)).expect("newest version");
        assert!(current.contains("newest synthetic version"), "{current}");
        assert!(!root.join("versions (2025-01-02)").exists(), "older copies stay out by default");

        for marker in ["synthetic top-level page", "synthetic second-level page", "synthetic third-level page", "synthetic next top-level page"] {
            assert!(page_with(&root.join("page-hierarchy"), page_file, marker).is_some(), "hierarchy page exists: {marker}");
        }
        let (_, formatted_page) = page_with(&root.join("formatted-text"), page_file, "synthetic plain run").expect("formatted page");
        assert!(formatted_page.contains("synthetic bold run") && formatted_page.contains("synthetic italic run"), "{formatted_page}");

        for (name, original) in &original_files {
            assert_eq!(fs::read(fixture(name)).expect("source remains readable"), *original, "import is read-only: {name}");
        }
    }
}
